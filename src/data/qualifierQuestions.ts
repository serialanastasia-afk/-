// Interleave questions across all domains so the student NEVER gets 10 questions of the same subject in a row!
function buildInterleavedQuestions(pool: QualifierQuestion[]): QualifierQuestion[] {
  const byDomain: Record<QualifierDomain, QualifierQuestion[]> = {
    general_culture: [],
    egypt_world: [],
    arabic: [],
    math: [],
    english: [],
    logic: [],
    observation: [],
    science: [],
    technology: [],
  };

  pool.forEach((q) => {
    byDomain[q.domain].push(q);
  });

  const domainCycle: QualifierDomain[] = [
    'arabic',
    'math',
    'science',
    'egypt_world',
    'english',
    'general_culture',
    'logic',
    'observation',
    'technology',
  ];

  const interleaved: QualifierQuestion[] = [];
  let added = true;
  while (added) {
    added = false;
    for (const dom of domainCycle) {
      const nextQ = byDomain[dom].shift();
      if (nextQ) {
        interleaved.push(nextQ);
        added = true;
      }
    }
  }
  return interleaved;
}

